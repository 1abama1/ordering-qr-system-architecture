CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE menu_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL CHECK (length(trim(name)) > 0), description TEXT, image_url TEXT,
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0 AND price <= 9999999.99),
  category_id BIGINT NOT NULL REFERENCES categories(id),
  is_available BOOLEAN NOT NULL DEFAULT true, is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE restaurant_tables (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number INTEGER NOT NULL UNIQUE CHECK (number > 0), is_active BOOLEAN NOT NULL DEFAULT true,
  qr_token_version INTEGER NOT NULL DEFAULT 1 CHECK (qr_token_version > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id BIGINT NOT NULL REFERENCES restaurant_tables(id),
  table_number_snapshot INTEGER NOT NULL CHECK (table_number_snapshot > 0),
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','COOKING','COMPLETED')),
  total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), completed_at TIMESTAMPTZ,
  idempotency_key VARCHAR(36) NOT NULL UNIQUE,
  request_fingerprint VARCHAR(64) NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL))
);
CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id), menu_item_id BIGINT NOT NULL REFERENCES menu_items(id),
  menu_item_name_snapshot VARCHAR(200) NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 100),
  price_at_order NUMERIC(12,2) NOT NULL CHECK (price_at_order >= 0),
  line_total NUMERIC(12,2) NOT NULL CHECK (line_total = price_at_order * quantity),
  UNIQUE(order_id, menu_item_id)
);
CREATE TABLE staff_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE CHECK (length(trim(username)) > 0),
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','KITCHEN')), enabled BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
